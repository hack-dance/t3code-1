import { describe, expect, it } from "vite-plus/test";

import { isReadOnlyCommand } from "./readOnlyCommands.ts";

describe("isReadOnlyCommand", () => {
  it.each([
    "ls",
    "ls -la /private/tmp/work",
    "pwd",
    "cat package.json",
    "head -n 20 src/index.ts",
    "head -n20 src/index.ts",
    "tail -50 log.txt",
    "wc -l a.ts b.ts",
    "cd packages/provider-muse && ls -la",
    "find . -maxdepth 2 -name package.json",
    "find src -type f -print",
    "grep -rn needle src",
    "tree -L 2 src",
    "uname -a",
    "which node",
  ])("accepts %s", (command) => {
    expect(isReadOnlyCommand(command)).toBe(true);
  });

  it.each([
    undefined,
    "",
    "cd src",
    "rm -rf /tmp/x",
    "touch result.txt",
    "ls > out.txt",
    "ls | sh",
    "ls; rm x",
    "ls & rm x",
    "echo $(id)",
    "cat `id`",
    "cat ~/.ssh/id_ed25519",
    "cat 'a b'",
    "FOO=1 ls",
    "ls\nrm x",
    "ls *",
    "git status",
    "git -C repo status --short",
    "git log --oneline -5",
    "git diff --ext-diff",
    "git -c core.pager=sh log",
    "git commit -m x",
    "rg --pre sh needle",
    "rg needle",
    "file -C -m /tmp/magic",
    "date -s 20300101",
    "df -h",
    "tree -o out.txt .",
    "tree -o/tmp/result .",
    "tree -L x",
    "ls --color=always",
    "ls --format",
    "cat -o x",
    "head -n x file",
    "grep -f patterns src",
    "find . -exec rm {} +",
    "find . -delete",
    "find . -fprint out",
    "find . -newer",
    "find . -fls out",
    "cd -P x && ls",
    "ls \u2014la",
    "npm test",
    "ls && touch x",
    "constructor",
    "constructor -x",
    "toString",
    "__proto__",
    "hasOwnProperty x",
    "\u00a0ls",
    "ls\u00a0&&pwd",
    "ls\r",
    "ls\u2028",
    "\u3000ls",
  ])("rejects %s", (command) => {
    expect(isReadOnlyCommand(command)).toBe(false);
  });
});
